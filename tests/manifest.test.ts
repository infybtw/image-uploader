import { expect, test } from "bun:test";
import manifest from "../extension/manifest.json";
import firefoxSettings from "../extension/firefox.json";
import chromeSettings from "../extension/chrome.json";
import { createManifest } from "../scripts/manifest";
import { SITE_MATCHES } from "../src/shared";

test("content scripts only run on Twitch/Kick; metadata requests may access HTTP(S) sites", () => {
  expect(manifest.manifest_version).toBe(3);
  expect(manifest.host_permissions).toEqual(["https://*/*", "http://*/*"]);
  expect(SITE_MATCHES).toEqual(["https://*.twitch.tv/*", "https://*.kick.com/*"]);
  expect("permissions" in manifest).toBe(false); // No tabs, clipboardRead or cookies permissions.
});

test("the common manifest contains no browser-specific fields", () => {
  expect("background" in manifest).toBe(false);
  expect("browser_specific_settings" in manifest).toBe(false);
  expect("minimum_chrome_version" in manifest).toBe(false);
});

test("browser settings do not duplicate shared metadata", () => {
  for (const settings of [firefoxSettings, chromeSettings]) {
    for (const key of Object.keys(settings)) expect(key in manifest).toBe(false);
  }
});

test("Firefox is generated from common metadata and Firefox-only settings", () => {
  const firefox = createManifest("firefox");
  expect(firefox).toEqual({ ...manifest, ...firefoxSettings });
  expect(firefox.browser_specific_settings.gecko.id).toBe("twir-paste@imageuploader.local");
  expect(firefox.browser_specific_settings.gecko.data_collection_permissions.required).toContain(
    "personalCommunications",
  );
  expect("minimum_chrome_version" in firefox).toBe(false);
});

test("Chrome metadata contains no Firefox-specific settings or extra permissions", () => {
  const chrome = createManifest("chrome");
  expect(chrome).toEqual({ ...manifest, ...chromeSettings });
  expect("minimum_chrome_version" in chrome && chrome.minimum_chrome_version).toBe("148");
  expect("browser_specific_settings" in chrome).toBe(false);
  expect("permissions" in chrome).toBe(false);
  expect(chrome.host_permissions).toEqual(manifest.host_permissions);
  expect("background" in chrome).toBe(false); // Generated by WXT from its entrypoint.
});

test("generated manifests cannot mutate shared data or browser settings", () => {
  const chrome = createManifest("chrome");
  const firefox = createManifest("firefox");
  chrome.host_permissions.push("https://example.com/*");
  firefox.browser_specific_settings.gecko.id = "changed@example.com";
  expect(createManifest("chrome")).toEqual({ ...manifest, ...chromeSettings });
  expect(createManifest("firefox")).toEqual({ ...manifest, ...firefoxSettings });
  expect(manifest.host_permissions).toEqual(["https://*/*", "http://*/*"]);
  expect(firefoxSettings.browser_specific_settings.gecko.id).toBe("twir-paste@imageuploader.local");
});
